import { chromium } from "/home/user/one/apps/e2e/node_modules/@playwright/test/index.mjs";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1180, height: 1400 }, deviceScaleFactor: 1.4 });
const errors = [];
p.on("pageerror", (e) => errors.push(String(e)));
await p.goto("file://" + process.argv[2]);
await p.waitForTimeout(400);
await p.screenshot({ path: process.argv[3], fullPage: false });
await p.click("button[data-act='theme'][data-value='light']");
await p.click("button[data-act='tenant'][data-value='2']");
await p.waitForTimeout(300);
await p.screenshot({ path: process.argv[4], fullPage: false });
await p.evaluate(() => window.scrollTo(0, 2200));
await p.waitForTimeout(200);
await p.screenshot({ path: process.argv[5] ?? "/tmp/a3.png" });
console.log("errors:", errors.length ? errors : "none");
await b.close();
